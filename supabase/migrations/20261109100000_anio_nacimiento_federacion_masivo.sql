-- Completa plantillas.fecha_nacimiento con el AÑO de nacimiento de la federación
-- (BD statsbomb, player_profile.birth_year; dump ffv_statsbomb_20261102_200113).
-- Reglas:
--   * Solo se rellenan jugadores SIN fecha_nacimiento: las fechas ya existentes NO se tocan.
--   * Se guarda AAAA-01-01 (marcador de año, no es el día/mes real).
--   * Coincidencia por nombre normalizado (sin tildes, orden de palabras indiferente) dentro de
--     los equipos propios de clubes Huesca. Si un nombre es ambiguo (varios años en la federación
--     o varios jugadores en la plantilla) se omite.
CREATE OR REPLACE FUNCTION pg_temp.norm_key(t text) RETURNS text LANGUAGE sql IMMUTABLE AS $f$
    SELECT string_agg(w, ' ' ORDER BY w) FROM unnest(regexp_split_to_array(
        btrim(regexp_replace(translate(upper(COALESCE(t,'')), 'ÁÉÍÓÚÜÀÈÌÒÙ', 'AEIOUUAEIOU'), '[^A-Z0-9Ñ ]', ' ', 'g')),
        '\s+')) w WHERE w <> ''
$f$;

