    CREATE TEMP TABLE fed_unico ON COMMIT DROP AS
        SELECT pg_temp.norm_key(nombre) AS k, min(anio) AS anio
        FROM fed_anio GROUP BY 1 HAVING count(DISTINCT anio) = 1;

    CREATE TEMP TABLE pl_huesca ON COMMIT DROP AS
        SELECT p.id, pg_temp.norm_key(p.nombre) AS k, p.fecha_nacimiento
        FROM plantillas p
        WHERE p.equipo_id IN (SELECT e.id FROM equipos e JOIN clubes c ON c.id = e.club_id
                              WHERE COALESCE(e.es_rival,false) = false AND c.nombre ILIKE '%huesca%');

    UPDATE plantillas p SET fecha_nacimiento = make_date(f.anio, 1, 1)
    FROM pl_huesca h JOIN fed_unico f ON f.k = h.k
    WHERE p.id = h.id
      AND p.fecha_nacimiento IS NULL
      AND (SELECT count(*) FROM pl_huesca h2 WHERE h2.k = h.k) = 1;
    GET DIAGNOSTICS n = ROW_COUNT;
    RAISE NOTICE 'Fechas (año) asignadas: %', n;
