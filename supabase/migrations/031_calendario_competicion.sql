-- =====================================================
-- Calendario completo de una competición externa (todas las
-- jornadas y partidos de la liga, no solo los del club).
-- Se usa para mostrar el calendario íntegro de una competición
-- (p.ej. federación), resaltando el equipo propio en la UI.
-- =====================================================

CREATE TABLE IF NOT EXISTS calendario_competicion (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    competicion_id UUID NOT NULL REFERENCES competiciones(id) ON DELETE CASCADE,
    jornada INT NOT NULL,
    fecha DATE NOT NULL,
    equipo_local VARCHAR(255) NOT NULL,
    equipo_visitante VARCHAR(255) NOT NULL,
    resultado VARCHAR(20),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_calendario_competicion_competicion ON calendario_competicion(competicion_id);
CREATE INDEX IF NOT EXISTS idx_calendario_competicion_jornada ON calendario_competicion(competicion_id, jornada);

DROP TRIGGER IF EXISTS trg_calendario_competicion_updated_at ON calendario_competicion;
CREATE TRIGGER trg_calendario_competicion_updated_at BEFORE UPDATE ON calendario_competicion FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

ALTER TABLE calendario_competicion ENABLE ROW LEVEL SECURITY;
CREATE POLICY "calendario_competicion: leer si autenticado" ON calendario_competicion
    FOR SELECT USING (auth.role() = 'authenticated');
CREATE POLICY "calendario_competicion: escribir si autenticado" ON calendario_competicion
    FOR ALL USING (auth.role() = 'authenticated') WITH CHECK (auth.role() = 'authenticated');

